    //   severity: "error",
    //   from: { path: "^src/shared/" },
    //   to: { path: "^src/(app|features)/" },
    // },
    // {
    //   name: "фича-не-знает-об-app",
    //   comment: "Оркестрация идёт сверху вниз. Импорт снизу вверх — это цикл, просто отложенный.",
    //   severity: "error",
    //   from: { path: "^src/features/" },
    //   to: { path: "^src/app/" },
    // },
    // {
