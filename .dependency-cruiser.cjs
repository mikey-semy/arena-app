    // тоже нет. Расчертить её заранее значит выдумать границы до того, как
    // стало понятно, где они проходят.
    //
    // Появились слои — раскомментируй и поправь под свои имена. Ниже — рабочий
    // пример: app оркестрирует, features не знают друг о друге, shared не знает
    // никого.
    //
    // {
    //   name: "shared-не-знает-о-верхних",
