    //   comment: "Кросс-импорт склеивает фичи намертво. Общее выносится в shared.",
    //   severity: "error",
    //   from: { path: "^src/features/([^/]+)/" },
    //   // $1 — та же фича, что слева. Себя импортировать можно, соседа нельзя.
