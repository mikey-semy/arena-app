// Границы слоёв — что кому можно импортировать.
//
// Общие правила (циклы, осиротевшие модули, неразрешимые импорты) не пишем сами:
// они взяты из пресета автора инструмента. Изобретать тут нечего, а поддерживать
// свою копию — значит отстать от неё через год.
//
//   just boundaries          проверить
//   just boundaries-freeze   заморозить то, что уже нарушено (см. ниже)
//
// Почему не eslint-plugin-boundaries: в проекте линтер — Biome, а плагин требует
// ESLint целиком. Тащить второй линтер ради одного правила дороже, чем взять
// отдельный инструмент. Там, где ESLint уже есть, разумнее обратное.
