// Ник для игры.
//
// Шрифт Quake 3 знает только латиницу, поэтому имя из Discord приходится
// приводить к ней. Та же таблица есть в оболочке клиента — это копия, и так
// и задумано: там она работает с билетом в браузере, здесь с профилем в базе,
// и связывать их одной зависимостью ради тридцати строк не стоит.
const CYRILLIC: Record<string, string> = {
  а: "a",
  б: "b",
  в: "v",
  г: "g",
  д: "d",
  е: "e",
  ё: "e",
  ж: "zh",
  з: "z",
  и: "i",
  й: "y",
  к: "k",
  л: "l",
  м: "m",
  н: "n",
  о: "o",
  п: "p",
  р: "r",
  с: "s",
  т: "t",
  у: "u",
  ф: "f",
  х: "h",
  ц: "c",
  ч: "ch",
  ш: "sh",
  щ: "sch",
  ъ: "",
  ы: "y",
  ь: "",
  э: "e",
  ю: "yu",
  я: "ya",
};

/** Приводит любое имя к тому, что Quake 3 сможет нарисовать. */
export function toNick(raw: string): string {
  const latin = [...raw.toLowerCase()].map((ch) => CYRILLIC[ch] ?? ch).join("");
  const clean = latin
    .replace(/[^a-z0-9_.[\]-]/g, "_")
    .replace(/_+/g, "_")
    .slice(0, 20);
  return clean.replace(/^_+|_+$/g, "") || "player";
}
