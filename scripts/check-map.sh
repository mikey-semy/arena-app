#!/usr/bin/env bash
# Тянет ли pro-q3dm6 текстуры из pak0 или несёт свои.
#
# Ответ решает не мелочь: если своих текстур нет, путь через свободный контент
# OpenArena закрыт, и раздача контента возможна только в закрытом контуре.
set -euo pipefail

PK3="${1:?укажи путь к pro-q3dm6.pk3}"

echo "— своё в pk3:"
unzip -l "${PK3}" | grep -E 'textures/|scripts/' || echo "  (ничего)"

echo
if unzip -l "${PK3}" | grep -q 'textures/'; then
  echo "ВЫВОД: свои текстуры есть — проверить, все ли, но шанс на OpenArena остаётся"
else
  echo "ВЫВОД: своих текстур нет → карта требует pak0 → только закрытый контур"
fi
