#!/usr/bin/env bash
# Забирает шрифты к себе и собирает src/app/fonts.css.
#
# Зачем самим, а не ссылкой на Google Fonts: сайт не должен переставать
# читаться из-за того, что до чужого CDN не достучались. Плюс запросов к
# третьей стороне за каждым посетителем не идёт.
#
# Выбор гарнитур определяется одним требованием: сайт русскоязычный, а
# у большинства «брутальных» гарнитур кириллицы нет вовсе. Здесь она есть
# у всех трёх, и все три под открытой лицензией (SIL OFL).
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
python3 scripts/fetch-fonts.py
